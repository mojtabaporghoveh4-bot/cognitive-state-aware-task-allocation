def boxed_legend(ax, **kwargs) -> None:
    legend = ax.legend(
        frameon=True,
        fancybox=False,
        framealpha=1.0,
        edgecolor="black",
        facecolor="white",
        **kwargs,
    )
    legend.get_frame().set_linewidth(0.6)


def save_figure_with_locked_pdf_fallback(fig, figures_dir: Path, stem: str) -> None:
    try:
        fig.savefig(figures_dir / f"{stem}.pdf")
    except PermissionError:
        fig.savefig(figures_dir / f"{stem}_updated.pdf")


def metric_direction_suffix(metric: str) -> str:
    return "LB" if metric in LOWER_IS_BETTER else "HB"


def ordered_scenarios(scenarios) -> List[str]:
    available = [str(scenario) for scenario in scenarios]
    return [scenario for scenario in SCENARIO_ORDER if scenario in available] + [
        scenario for scenario in sorted(available) if scenario not in SCENARIO_ORDER
    ]


def add_dynamic_disturbance_markers(ax, scenario: str) -> None:
    if scenario != "dynamic_disturbance":
        return
    for time in DYNAMIC_DISTURBANCE_TIMES:
        ax.axvline(time, color="#5f5f5f", linestyle="--", linewidth=0.8, alpha=0.45, zorder=0)


def load_results(input_dir: Path) -> Dict[str, pd.DataFrame]:
    detailed_path = input_dir / "detailed_run_metrics.csv"
    assignment_path = input_dir / "assignment_log.csv"
    summary_path = input_dir / "summary_metrics.csv"
    trajectory_path = input_dir / "state_trajectories.csv"
    if not detailed_path.exists():
        raise FileNotFoundError(f"Missing {detailed_path}")
    if not assignment_path.exists():
        raise FileNotFoundError(f"Missing {assignment_path}")

    return {
        "detailed": pd.read_csv(detailed_path),
        "assignments": pd.read_csv(assignment_path),
        "summary": pd.read_csv(summary_path) if summary_path.exists() else pd.DataFrame(),
        "trajectories": pd.read_csv(trajectory_path) if trajectory_path.exists() else pd.DataFrame(),
    }


def ordered_methods(methods: List[str]) -> List[str]:
    return [method for method in METHODS if method in methods] + [method for method in methods if method not in METHODS]


def save_metric_tables(detailed: pd.DataFrame, output_dir: Path) -> pd.DataFrame:
    grouped = detailed.groupby(["scenario", "method"], as_index=False)[METRICS].agg(["mean", "std"])
    grouped.columns = ["_".join(col).strip("_") for col in grouped.columns.to_flat_index()]
    grouped = grouped.rename(columns={"scenario_": "scenario", "method_": "method"})
    grouped.to_csv(output_dir / "metric_summary_mean_std.csv", index=False)

    compact_rows = []
    for _, row in grouped.iterrows():
        out = {
            "Scenario": SCENARIO_LABELS.get(str(row["scenario"]), str(row["scenario"])),
            "Method": METHOD_LABELS.get(str(row["method"]), str(row["method"])),
        }
        for metric in METRICS:
            out[metric] = f"{row[f'{metric}_mean']:.3f} +/- {row[f'{metric}_std']:.3f}"
        compact_rows.append(out)
    compact = pd.DataFrame(compact_rows)
    compact.to_csv(output_dir / "metric_summary_compact.csv", index=False)
    return compact


def save_metric_plots(detailed: pd.DataFrame, output_dir: Path) -> None:
    figures_dir = output_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)

    for scenario in ordered_scenarios(detailed["scenario"].unique()):
        subset = detailed[detailed["scenario"] == scenario]
        methods = ordered_methods(list(subset["method"].unique()))
        labels = [METHOD_LABELS.get(method, method) for method in methods]

        for metric in METRICS:
            means = [subset.loc[subset["method"] == method, metric].mean() for method in methods]
            stds = [subset.loc[subset["method"] == method, metric].std() for method in methods]

            fig, ax = plt.subplots(figsize=(8.5, 4.8))
            ax.bar(range(len(methods)), means, yerr=stds, capsize=4, color=BAR_COLOR, edgecolor="black", linewidth=0.6)
            ax.set_xticks(range(len(methods)))
            ax.set_xticklabels(labels, rotation=25, ha="right")
            ax.set_ylabel(METRIC_LABELS.get(metric, metric))
            fig.tight_layout()
            suffix = metric_direction_suffix(metric)
            fig.savefig(figures_dir / f"{scenario}_{metric}_{suffix}.pdf")
            plt.close(fig)


def save_grouped_metric_overview(detailed: pd.DataFrame, output_dir: Path) -> None:
    figures_dir = output_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)

    scenarios = ordered_scenarios(detailed["scenario"].unique())
    methods = ordered_methods(list(detailed["method"].unique()))
    scenario_labels = [SCENARIO_LABELS.get(str(scenario), str(scenario)) for scenario in scenarios]
    bar_width = 0.14
    x_centers = list(range(len(scenarios)))
    offsets = [(idx - (len(methods) - 1) / 2) * bar_width for idx in range(len(methods))]

    fig, axes = plt.subplots(2, 3, figsize=(14.0, 7.8))
    flat_axes = list(axes.flat)

    for metric_index, metric in enumerate(METRICS):
        ax = flat_axes[metric_index]
        for method_index, method in enumerate(methods):
            means = []
            for scenario in scenarios:
                values = detailed.loc[
                    (detailed["scenario"] == scenario) & (detailed["method"] == method),
                    metric,
                ]
                means.append(values.mean())
            positions = [center + offsets[method_index] for center in x_centers]
            ax.bar(
                positions,
                means,
                width=bar_width,
                color=GROUPED_METRIC_COLORS.get(method, BAR_COLOR),
                edgecolor="black",
                linewidth=0.5,
                hatch=GROUPED_METRIC_HATCHES.get(method, ""),
                label=METHOD_LABELS.get(method, method),
            )

        ax.set_xticks(x_centers)
        ax.set_xticklabels(scenario_labels, rotation=18, ha="right")
        ax.set_ylabel(METRIC_LABELS.get(metric, metric))

    legend_ax = flat_axes[-1]
    legend_ax.axis("off")
    handles = [
        Patch(
            facecolor=GROUPED_METRIC_COLORS.get(method, BAR_COLOR),
            edgecolor="black",
            hatch=GROUPED_METRIC_HATCHES.get(method, ""),
            label=METHOD_LABELS.get(method, method),
        )
        for method in methods
    ]
    legend = legend_ax.legend(
        handles=handles,
        loc="center",
        frameon=True,
        fancybox=False,
        framealpha=1.0,
        edgecolor="black",
        facecolor="white",
    )
    legend.get_frame().set_linewidth(0.6)

    fig.tight_layout()
    fig.savefig(figures_dir / "overall_performance_metrics_grouped.pdf")
    plt.close(fig)


def save_cost_component_outputs(detailed: pd.DataFrame, output_dir: Path) -> pd.DataFrame:
    component_cols = list(COST_COMPONENT_WEIGHTS)
    components = detailed[["scenario", "method", "run", "seed"]].copy()
    components["method_label"] = components["method"].map(lambda value: METHOD_LABELS.get(str(value), str(value)))
    components["weighted_tardiness"] = detailed["TWT"] * COST_COMPONENT_WEIGHTS["weighted_tardiness"]
    components["deadline_miss_penalty"] = detailed["DMR"] * COST_COMPONENT_WEIGHTS["deadline_miss_penalty"]
    components["incomplete_work_penalty"] = (1.0 - detailed["WCR"]) * COST_COMPONENT_WEIGHTS["incomplete_work_penalty"]
    components["cumulative_impairment_penalty"] = (
        detailed["CI"] * COST_COMPONENT_WEIGHTS["cumulative_impairment_penalty"]
    )
    components["peak_impairment_penalty"] = detailed["PI"] * COST_COMPONENT_WEIGHTS["peak_impairment_penalty"]
    components["evaluation_cost"] = components[component_cols].sum(axis=1)
    components.to_csv(output_dir / "cost_components_by_run.csv", index=False)

    method_order = {method: i for i, method in enumerate(METHODS)}
    summary = components.groupby(["scenario", "method", "method_label"], as_index=False)[
        component_cols + ["evaluation_cost"]
    ].mean()
    summary["method_order"] = summary["method"].map(method_order).fillna(999)
    summary = summary.sort_values(["scenario", "method_order"]).drop(columns=["method_order"])
    summary.to_csv(output_dir / "cost_component_summary.csv", index=False)

    figures_dir = output_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    for scenario in ordered_scenarios(summary["scenario"].unique()):
        subset = summary[summary["scenario"] == scenario].copy()
        methods = ordered_methods(list(subset["method"].unique()))
        subset["method_order"] = subset["method"].map({method: i for i, method in enumerate(methods)})
        subset = subset.sort_values("method_order")

        normalized = subset[component_cols].copy()
        for col in component_cols:
            scale = max(float(normalized[col].max()), 1e-9)
            normalized[col] = normalized[col] / scale

        x = list(range(len(subset)))
        bottom = [0.0] * len(subset)
        fig, ax = plt.subplots(figsize=(9.2, 5.0))
        for col in component_cols:
            values = list(normalized[col])
            ax.bar(
                x,
                values,
                bottom=bottom,
                color=COST_COMPONENT_COLORS[col],
                edgecolor="black",
                linewidth=0.5,
                label=COST_COMPONENT_LABELS[col],
            )
            bottom = [b + v for b, v in zip(bottom, values)]

        ax.set_xticks(x)
        ax.set_xticklabels(subset["method_label"], rotation=25, ha="right")
        ax.set_ylabel("Normalized weighted cost component")
        boxed_legend(ax, ncol=2)
        fig.tight_layout()
        fig.savefig(figures_dir / f"{scenario}_evaluation_cost_decomposition_LB.pdf")
        plt.close(fig)

    return summary


def reconstruct_overload_unfinished_tasks(detailed: pd.DataFrame, assignments: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict[str, object]] = []
    overload = detailed[detailed["scenario"] == "overload_finite_shift"]

    for _, metric_row in overload.iterrows():
        method = str(metric_row["method"])
        run = int(metric_row["run"])
        seed = int(metric_row["seed"])
        data = make_paper_scenario("overload_finite_shift", seed=seed)
        tf = data.mission_horizon

        run_assignments = assignments[
            (assignments["scenario"] == "overload_finite_shift")
            & (assignments["method"] == method)
            & (assignments["run"] == run)
        ].copy()

        starts_by_task: Dict[int, Dict[str, object]] = {}
        for _, assignment in run_assignments.iterrows():
            task_index = int(assignment["task"]) - 1
            starts_by_task[task_index] = {
                "start_time": int(assignment["time"]),
                "operator": int(assignment["operator"]),
                "robot": int(assignment["robot"]),
            }

        for task in data.tasks:
            start = starts_by_task.get(task.task_id)
            if start is None:
                rows.append(
                    {
                        "scenario": "overload_finite_shift",
                        "method": method,
                        "method_label": METHOD_LABELS.get(method, method),
                        "run": run,
                        "seed": seed,
                        "task": task.task_id + 1,
                        "priority": task.priority,
                        "duration": task.processing_time,
                        "due": task.due,
                        "release": task.release,
                        "start_time": "",
                        "completion_time": "",
                        "operator": "",
                        "robot": "",
                        "unfinished_reason": "never_started",
                    }
                )
                continue

            completion_time = int(start["start_time"]) + task.processing_time
            if completion_time > tf:
                rows.append(
                    {
                        "scenario": "overload_finite_shift",
                        "method": method,
                        "method_label": METHOD_LABELS.get(method, method),
                        "run": run,
                        "seed": seed,
                        "task": task.task_id + 1,
                        "priority": task.priority,
                        "duration": task.processing_time,
                        "due": task.due,
                        "release": task.release,
                        "start_time": start["start_time"],
                        "completion_time": completion_time,
                        "operator": start["operator"],
                        "robot": start["robot"],
                        "unfinished_reason": "started_but_finishes_after_Tf",
                    }
                )

    return pd.DataFrame(rows)


def save_unfinished_task_outputs(detailed: pd.DataFrame, assignments: pd.DataFrame, output_dir: Path) -> pd.DataFrame:
    unfinished = reconstruct_overload_unfinished_tasks(detailed, assignments)
    unfinished.to_csv(output_dir / "overload_unfinished_tasks_by_run.csv", index=False)

    if unfinished.empty:
        summary = pd.DataFrame(columns=["method", "method_label", "unfinished_count_mean"])
    else:
        summary = (
            unfinished.groupby(["method", "method_label", "run"], as_index=False)
            .agg(
                unfinished_count=("task", "count"),
                unfinished_priority_sum=("priority", "sum"),
                high_priority_unfinished=("priority", lambda values: int((values == 4).sum())),
                never_started=("unfinished_reason", lambda values: int((values == "never_started").sum())),
                started_late=("unfinished_reason", lambda values: int((values == "started_but_finishes_after_Tf").sum())),
            )
            .groupby(["method", "method_label"], as_index=False)
            .agg(
                unfinished_count_mean=("unfinished_count", "mean"),
                unfinished_count_std=("unfinished_count", "std"),
                unfinished_priority_sum_mean=("unfinished_priority_sum", "mean"),
                unfinished_priority_sum_std=("unfinished_priority_sum", "std"),
                high_priority_unfinished_mean=("high_priority_unfinished", "mean"),
                never_started_mean=("never_started", "mean"),
                started_late_mean=("started_late", "mean"),
            )
        )
        summary["unfinished_count_std"] = summary["unfinished_count_std"].fillna(0.0)
        summary["unfinished_priority_sum_std"] = summary["unfinished_priority_sum_std"].fillna(0.0)

    method_order = {method: index for index, method in enumerate(METHODS)}
    summary = summary.sort_values("method", key=lambda col: col.map(method_order).fillna(999))
    summary.to_csv(output_dir / "overload_unfinished_summary_by_method.csv", index=False)

    if not summary.empty:
        figures_dir = output_dir / "figures"
        figures_dir.mkdir(parents=True, exist_ok=True)

        fig, axes = plt.subplots(2, 2, figsize=(13.5, 8.8))
        flat_axes = list(axes.flat)
        x = list(range(len(summary)))

        flat_axes[0].bar(
            x,
            summary["unfinished_count_mean"],
            yerr=summary["unfinished_count_std"],
            capsize=4,
            color=BAR_COLOR,
            edgecolor="black",
            linewidth=0.6,
        )
        flat_axes[0].set_xticks(x)
        flat_axes[0].set_xticklabels(summary["method_label"], rotation=25, ha="right")
        flat_axes[0].set_ylabel(r"Number of unfinished tasks at $T_f$")
        flat_axes[0].set_title("Unfinished task count", pad=10)

        flat_axes[1].bar(
            x,
            summary["unfinished_priority_sum_mean"],
            yerr=summary["unfinished_priority_sum_std"],
            capsize=4,
            color=BAR_COLOR,
            edgecolor="black",
            linewidth=0.6,
        )
        flat_axes[1].set_xticks(x)
        flat_axes[1].set_xticklabels(summary["method_label"], rotation=25, ha="right")
        flat_axes[1].set_ylabel(r"Sum of unfinished task priorities at $T_f$")
        flat_axes[1].set_title("Unfinished priority weight", pad=10)

        bottom = [0.0] * len(summary)
        reason_colors = {
            "Never started": "#6f8faf",
            "Finishes after $T_f$": "#b86b6b",
        }
        for label, col in [
            ("Never started", "never_started_mean"),
            ("Finishes after $T_f$", "started_late_mean"),
        ]:
            values = list(summary[col])
            flat_axes[2].bar(
                x,
                values,
                bottom=bottom,
                color=reason_colors[label],
                edgecolor="black",
                linewidth=0.6,
                label=label,
            )
            bottom = [b + v for b, v in zip(bottom, values)]
        flat_axes[2].set_xticks(x)
        flat_axes[2].set_xticklabels(summary["method_label"], rotation=25, ha="right")
        flat_axes[2].set_ylabel(r"Number of unfinished tasks at $T_f$")
        flat_axes[2].set_title("Unfinished-task reason", pad=10)
        boxed_legend(flat_axes[2], loc="lower left")

        if not unfinished.empty:
            overload_runs = detailed[detailed["scenario"] == "overload_finite_shift"].groupby("method")["run"].nunique()
            profile = (
                unfinished.groupby(["method", "method_label", "priority", "duration"], as_index=False)
                .agg(unfinished_occurrences=("task", "count"))
            )
            profile["mean_count_per_run"] = profile.apply(
                lambda row: row["unfinished_occurrences"] / max(float(overload_runs.get(row["method"], 1.0)), 1.0),
                axis=1,
            )
            max_count = max(float(profile["mean_count_per_run"].max()), 1e-9)
            methods = ordered_methods(list(summary["method"].unique()))
            offsets = {method: (idx - (len(methods) - 1) / 2) * 0.07 for idx, method in enumerate(methods)}
