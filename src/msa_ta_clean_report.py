def soft_cluster_belief(z_value: float, sigma_z: float, n_clusters: int = 3) -> List[float]:
    thresholds = [k / n_clusters for k in range(n_clusters + 1)]
    midpoints = [(thresholds[k] + thresholds[k + 1]) / 2.0 for k in range(n_clusters)]
    sigma_sq = max(sigma_z, 1e-9) ** 2
    raw = [exp(-((z_value - midpoint) ** 2) / (2.0 * sigma_sq)) for midpoint in midpoints]
    total = sum(raw)
    return [value / total for value in raw]


def state_beliefs_from_row(state_row: pd.Series, params: ModelParams, operator_indices: List[int]) -> Dict[int, List[float]]:
    beliefs: Dict[int, List[float]] = {}
    for operator in operator_indices:
        fatigue = float(state_row[f"operator_{operator}_fatigue"])
        stress = float(state_row[f"operator_{operator}_stress"])
        z_value = min(1.0, max(0.0, params.omega_f * fatigue + params.omega_s * stress + params.omega_fs * fatigue * stress))
        beliefs[operator] = soft_cluster_belief(z_value, params.sigma_z, params.n_clusters)
    return beliefs


def mental_cost_from_beliefs(beliefs: Dict[int, List[float]], params: ModelParams) -> float:
    total = 0.0
    for belief in beliefs.values():
        for k, value in enumerate(belief):
            total += params.delta_w * (k**2) * value
    return total


def assignment_risk_from_rows(
    action_rows: pd.DataFrame,
    beliefs: Dict[int, List[float]],
    params: ModelParams,
) -> float:
    if action_rows.empty:
        return 0.0
    total = 0.0
    for _, assignment in action_rows.iterrows():
        operator = int(assignment["operator"])
        priority = float(assignment["priority"])
        belief = beliefs.get(operator, [])
        lambda_bar = 0.0
        for k, value in enumerate(belief):
            lambda_bar += (k / max(params.n_clusters - 1, 1)) * value
        total += lambda_bar * priority
    return total


def task_completion_times(data, run_assignments: pd.DataFrame) -> Dict[int, float]:
    completions = {task.task_id: float("inf") for task in data.tasks}
    for _, assignment in run_assignments.iterrows():
        task_id = int(assignment["task"]) - 1
        completion = int(assignment["time"]) + int(assignment["duration"])
        completions[task_id] = min(completions[task_id], float(completion))
    return completions


