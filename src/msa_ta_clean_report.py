            flat_axes[3].set_ylabel("Priority")
            flat_axes[3].set_yticks(sorted(unfinished["priority"].unique()))
            flat_axes[3].set_xlim(float(unfinished["duration"].min()) - 0.45, float(unfinished["duration"].max()) + 0.45)
