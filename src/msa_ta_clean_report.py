    mental_time_summary = compute_mental_state_time_summary(trajectories, scenario_sigmas)
    operator_mental_time_summary = compute_operator_mental_state_time_summary(trajectories, scenario_sigmas)
    trajectory_summary = compute_mental_trajectory_summary(trajectories)

    mental_time_summary.to_csv(output_dir / "mental_state_time_summary_by_method.csv", index=False)
    operator_mental_time_summary.to_csv(output_dir / "operator_mental_state_time_summary_by_method.csv", index=False)
    trajectory_summary.to_csv(output_dir / "operator_mental_state_trajectory_summary.csv", index=False)

    save_mental_state_time_figures(mental_time_summary, output_dir)
    save_grouped_mental_state_time_overview(mental_time_summary, output_dir)
    save_grouped_operator_mental_state_time_overview(operator_mental_time_summary, output_dir)
    save_mental_trajectory_figures(trajectory_summary, output_dir)
    return mental_time_summary


