        if df.empty:
            return ""
        columns = [str(col) for col in df.columns]
        rows = ["| " + " | ".join(columns) + " |"]
        rows.append("| " + " | ".join("---" for _ in columns) + " |")
        for _, row in df.iterrows():
            rows.append("| " + " | ".join(str(row[col]) for col in df.columns) + " |")
