def save_instantaneous_cost_outputs(
    input_dir: Path,
    detailed: pd.DataFrame,
    assignments: pd.DataFrame,
    trajectories: pd.DataFrame,
    output_dir: Path,
) -> pd.DataFrame:
    if trajectories.empty:
        empty = pd.DataFrame()
        empty.to_csv(output_dir / "instantaneous_cost_summary.csv", index=False)
        return empty

    scenario_params = load_scenario_params(input_dir)
    operator_indices = operator_indices_from_trajectories(trajectories)
    rows: List[Dict[str, object]] = []

    for _, metric_row in detailed.iterrows():
        scenario = str(metric_row["scenario"])
        method = str(metric_row["method"])
        run = int(metric_row["run"])
        seed = int(metric_row["seed"])
        tuned_for = str(metric_row.get("tuned_for_scenario", scenario))
        params = scenario_params.get(tuned_for, scenario_params.get(scenario, ModelParams()))
        data = make_paper_scenario(scenario, seed=seed)

        run_assignments = assignments[
            (assignments["scenario"] == scenario)
            & (assignments["method"] == method)
            & (assignments["run"] == run)
        ].copy()
        completions = task_completion_times(data, run_assignments)
        run_states = trajectories[
            (trajectories["scenario"] == scenario)
            & (trajectories["method"] == method)
            & (trajectories["run"] == run)
        ].sort_values("time")

        for _, state_row in run_states.iterrows():
            time = int(state_row["time"])
            if time >= data.mission_horizon:
                continue

            known_tasks = [task for task in data.tasks if task.release <= time]
            c_u = sum(task.priority for task in known_tasks if completions[task.task_id] > time)
            c_o = sum(
                task.priority
                for task in known_tasks
                if completions[task.task_id] > time and time > task.due
            )
            beliefs = state_beliefs_from_row(state_row, params, operator_indices)
            c_m = mental_cost_from_beliefs(beliefs, params)
            action_rows = run_assignments[run_assignments["time"] == time]
            c_r = assignment_risk_from_rows(action_rows, beliefs, params)

            alpha_c_u = params.alpha * c_u
            beta_c_m = params.beta * c_m
            gamma_c_r = params.gamma * c_r
            eta_c_o = params.eta * c_o
            rows.append(
                {
                    "scenario": scenario,
                    "method": method,
                    "method_label": METHOD_LABELS.get(method, method),
                    "run": run,
                    "seed": seed,
                    "time": time,
                    "C_u": c_u,
                    "C_m": c_m,
                    "C_r": c_r,
                    "C_o": c_o,
                    "alpha": params.alpha,
                    "beta": params.beta,
                    "gamma": params.gamma,
                    "eta": params.eta,
                    "alpha_C_u": alpha_c_u,
                    "beta_C_m": beta_c_m,
                    "gamma_C_r": gamma_c_r,
                    "eta_C_o": eta_c_o,
                    "C_t": alpha_c_u + beta_c_m + gamma_c_r + eta_c_o,
                }
            )

    instant = pd.DataFrame(rows)
    instant.to_csv(output_dir / "instantaneous_cost_components_by_time.csv", index=False)
    if instant.empty:
        empty = pd.DataFrame()
        empty.to_csv(output_dir / "instantaneous_cost_summary.csv", index=False)
        return empty
    save_instantaneous_cost_trajectory_figures(instant, output_dir)
    save_instantaneous_component_trajectory_figures(instant, output_dir)

    by_run = (
        instant.groupby(["scenario", "method", "method_label", "run"], as_index=False)[
            ["C_u", "C_m", "C_r", "C_o", *INSTANT_COST_COMPONENTS, "C_t"]
        ]
        .sum()
        .rename(
            columns={
                "C_u": "sum_C_u",
                "C_m": "sum_C_m",
                "C_r": "sum_C_r",
                "C_o": "sum_C_o",
                "C_t": "sum_C_t",
            }
        )
    )
    by_run.to_csv(output_dir / "instantaneous_cost_components_by_run.csv", index=False)

    method_order = {method: index for index, method in enumerate(METHODS)}
    summary = by_run.groupby(["scenario", "method", "method_label"], as_index=False)[
        ["sum_C_u", "sum_C_m", "sum_C_r", "sum_C_o", *INSTANT_COST_COMPONENTS, "sum_C_t"]
    ].mean()
    summary["method_order"] = summary["method"].map(method_order).fillna(999)
    summary = summary.sort_values(["scenario", "method_order"]).drop(columns=["method_order"])
    summary.to_csv(output_dir / "instantaneous_cost_summary.csv", index=False)

    figures_dir = output_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    for scenario in ordered_scenarios(summary["scenario"].unique()):
        subset = summary[summary["scenario"] == scenario].copy()
        fig, ax = plt.subplots(figsize=(9.2, 5.0))
        draw_instantaneous_decomposition_panel(ax, subset)
        boxed_legend(ax, ncol=2)
        fig.tight_layout()
        fig.savefig(figures_dir / f"{scenario}_instantaneous_cost_decomposition_LB.pdf")
        plt.close(fig)

    save_combined_instantaneous_cost_decomposition(summary, output_dir)
    save_combined_instantaneous_cost_decomposition(summary, output_dir, normalize_components=True)
    return summary


def operator_indices_from_trajectories(trajectories: pd.DataFrame) -> List[int]:
    indices = []
    for col in trajectories.columns:
        if col.startswith("operator_") and col.endswith("_impairment"):
            indices.append(int(col.split("_")[1]))
    return sorted(indices)


def compute_mental_state_time_summary(
    trajectories: pd.DataFrame,
    scenario_sigmas: Dict[str, float],
) -> pd.DataFrame:
    if trajectories.empty:
        return pd.DataFrame()

    operator_indices = operator_indices_from_trajectories(trajectories)
    rows: List[Dict[str, object]] = []
    group_cols = ["scenario", "method", "run"]

    for (scenario, method, run), group in trajectories.groupby(group_cols):
        sigma_z = scenario_sigmas.get(str(scenario), 0.12)
        fresh = nominal = degraded = 0.0
        for _, state_row in group.iterrows():
            for operator in operator_indices:
                z_value = float(state_row[f"operator_{operator}_impairment"])
                belief = soft_cluster_belief(z_value, sigma_z)
                fresh += belief[0]
                nominal += belief[1]
                degraded += belief[2]

        n_operators = max(len(operator_indices), 1)
        horizon_steps = group["time"].nunique()
        rows.append(
            {
                "scenario": scenario,
                "method": method,
                "method_label": METHOD_LABELS.get(str(method), str(method)),
                "run": run,
                "fresh_time_per_operator": fresh / n_operators,
                "nominal_time_per_operator": nominal / n_operators,
                "degraded_time_per_operator": degraded / n_operators,
                "non_relaxed_time_per_operator": (nominal + degraded) / n_operators,
                "degraded_time_ratio": degraded / max(n_operators * horizon_steps, 1),
                "non_relaxed_time_ratio": (nominal + degraded) / max(n_operators * horizon_steps, 1),
            }
        )

    run_level = pd.DataFrame(rows)
    summary = (
        run_level.groupby(["scenario", "method", "method_label"], as_index=False)
        .agg(
            fresh_time_mean=("fresh_time_per_operator", "mean"),
            nominal_time_mean=("nominal_time_per_operator", "mean"),
            degraded_time_mean=("degraded_time_per_operator", "mean"),
            non_relaxed_time_mean=("non_relaxed_time_per_operator", "mean"),
            degraded_time_ratio_mean=("degraded_time_ratio", "mean"),
            non_relaxed_time_ratio_mean=("non_relaxed_time_ratio", "mean"),
        )
    )
    method_order = {method: index for index, method in enumerate(METHODS)}
    return summary.sort_values(["scenario", "method"], key=lambda col: col.map(method_order).fillna(col))


def compute_operator_mental_state_time_summary(
    trajectories: pd.DataFrame,
    scenario_sigmas: Dict[str, float],
) -> pd.DataFrame:
    if trajectories.empty:
        return pd.DataFrame()

    operator_indices = operator_indices_from_trajectories(trajectories)
    rows: List[Dict[str, object]] = []

    for (scenario, method, run), group in trajectories.groupby(["scenario", "method", "run"]):
        sigma_z = scenario_sigmas.get(str(scenario), 0.12)
        for operator in operator_indices:
            fresh = nominal = degraded = 0.0
            for _, state_row in group.iterrows():
                z_value = float(state_row[f"operator_{operator}_impairment"])
                belief = soft_cluster_belief(z_value, sigma_z)
                fresh += belief[0]
                nominal += belief[1]
                degraded += belief[2]
            horizon_steps = group["time"].nunique()
            rows.append(
                {
                    "scenario": scenario,
                    "method": method,
                    "method_label": METHOD_LABELS.get(str(method), str(method)),
                    "run": run,
                    "operator": operator,
                    "fresh_time": fresh,
                    "nominal_time": nominal,
                    "degraded_time": degraded,
                    "non_relaxed_time": nominal + degraded,
                    "degraded_time_ratio": degraded / max(horizon_steps, 1),
                    "non_relaxed_time_ratio": (nominal + degraded) / max(horizon_steps, 1),
                }
            )

    run_level = pd.DataFrame(rows)
    summary = (
        run_level.groupby(["scenario", "method", "method_label", "operator"], as_index=False)
        .agg(
            fresh_time_mean=("fresh_time", "mean"),
            nominal_time_mean=("nominal_time", "mean"),
            degraded_time_mean=("degraded_time", "mean"),
            non_relaxed_time_mean=("non_relaxed_time", "mean"),
            degraded_time_ratio_mean=("degraded_time_ratio", "mean"),
            non_relaxed_time_ratio_mean=("non_relaxed_time_ratio", "mean"),
        )
    )
    method_order = {method: index for index, method in enumerate(METHODS)}
    summary["method_order"] = summary["method"].map(method_order).fillna(999)
    return summary.sort_values(["scenario", "operator", "method_order"]).drop(columns=["method_order"])


def draw_grouped_mental_state_bars(ax, data: pd.DataFrame, value_col: str, ylabel: str = "") -> None:
    scenarios = ordered_scenarios(data["scenario"].unique())
    methods = ordered_methods(list(data["method"].unique()))
    scenario_labels = [SCENARIO_LABELS.get(str(scenario), str(scenario)) for scenario in scenarios]
    bar_width = min(0.15, 0.72 / max(len(methods), 1))
    x_centers = list(range(len(scenarios)))
    offsets = [(idx - (len(methods) - 1) / 2) * bar_width for idx in range(len(methods))]

    for method_index, method in enumerate(methods):
        means = []
        for scenario in scenarios:
            values = data.loc[(data["scenario"] == scenario) & (data["method"] == method), value_col]
            means.append(values.mean())
        positions = [center + offsets[method_index] for center in x_centers]
        ax.bar(
            positions,
            means,
            width=bar_width,
            color=GROUPED_METRIC_COLORS.get(method, BAR_COLOR),
            edgecolor="black",
            linewidth=0.5,
            label=METHOD_LABELS.get(method, method),
        )

    ax.set_xticks(x_centers)
    ax.set_xticklabels(scenario_labels, rotation=18, ha="right")
    if ylabel:
        ax.set_ylabel(ylabel)


def draw_stacked_mental_state_distribution(ax, data: pd.DataFrame, ylabel: str = "") -> None:
    methods = ordered_methods(list(data["method"].unique()))
    ordered = data.copy()
    ordered["method_order"] = ordered["method"].map({method: i for i, method in enumerate(methods)})
    ordered = ordered.sort_values("method_order")

    x = list(range(len(ordered)))
    bottom = [0.0] * len(ordered)
    totals = [0.0] * len(ordered)
    for label, col in [
        ("Fresh", "fresh_time_mean"),
        ("Nominal", "nominal_time_mean"),
        ("Degraded", "degraded_time_mean"),
    ]:
        values = list(ordered[col])
        totals = [total + value for total, value in zip(totals, values)]
        ax.bar(
            x,
            values,
            bottom=bottom,
            color=STACK_COLORS[label.lower()],
            edgecolor="black",
            linewidth=0.6,
            label=label,
        )
        bottom = [b + v for b, v in zip(bottom, values)]

    ax.set_xticks(x)
    ax.set_xticklabels(ordered["method_label"], rotation=25, ha="right")
    if ylabel:
        ax.set_ylabel(ylabel)
    if totals:
        ax.set_ylim(0, max(totals) * 1.08)


